const LANG = {
  ".mjs": "js",
  ".ts": "ts",
  ".json": "json",
  ".jsonc": "jsonc",
  ".md": "md",
  ".astro": "astro",
  ".css": "css",
  ".yml": "yaml",
};

function fenceFor(text) {
  const longest = Math.max(
    2,
    ...[...text.matchAll(/^\s*(`{3,})/gm)].map((m) => m[1].length),
  );
  return "`".repeat(longest + 1);
}

function embed(file) {
  const text = readFileSync(path.join(ROOT, file), "utf8");
  const fence = fenceFor(text);
  const lang = LANG[path.extname(file)] ?? "";
  // The file's final newline is part of the file: the closing fence goes on the line after it.
  return `#### \`${file}\`\n\n${fence}${lang}\n${text}${text.endsWith("\n") ? "" : "\n"}${fence}\n`;
}

const commit = execSync("git rev-parse --short HEAD", { cwd: ROOT })
  .toString()
  .trim();
const dirty = execSync("git status --porcelain -- . ':!docs'", { cwd: ROOT })
  .toString()
  .trim();
const guide = readFileSync(path.join(HERE, "PORT-GUIDE.md"), "utf8");

const out = [
  "<!-- Generated by docs/blog-system-port/build-handoff.mjs. Do not edit: change PORT-GUIDE.md or the sources, then regenerate. -->",
  "",
  `> Self-contained handoff, generated from commit \`${commit}\`${dirty ? " plus uncommitted changes" : ""}.`,
  "> It is the porting guide followed by an appendix with every file, byte for byte. Give this single file",
  '> to Claude Code in the target Astro project and say: "follow HANDOFF.md to install the blog system".',
  "> Where the guide says to copy a file from `$SRC`, write it from the appendix at the path in its heading.",
  "",
  guide.trimEnd(),
  "",
  "---",
  "",
  "## Appendix: the files",
  "",
  "Each heading is the path from the project root. The content between the fences is the exact file.",
  "",
];

let count = 0;
for (const [title, files] of SECTIONS) {
  const missing = files.filter((f) => !existsSync(path.join(ROOT, f)));
  if (missing.length) throw new Error(`missing files: ${missing.join(", ")}`);
  out.push(`### ${title}`, "");
  for (const f of files) {
    out.push(embed(f));
    count++;
  }
}

const target = path.join(HERE, "HANDOFF.md");
writeFileSync(target, out.join("\n"));
console.log(
  `✓ ${path.relative(ROOT, target)}: ${count} files, ${Math.round(out.join("\n").length / 1024)} kB`,
);
